#!/usr/bin/env python3
"""
Генератор входа для замеров Р3. Печатает в stdout вход по io-format.md:
обучающую выборку из N синтетических писем трёх классов (ham / spam / phish)
и небольшое число запросов. Письма собираются из словарей классов, общих
слов и редких «шумовых» слов, так что словарь растёт вместе с N.

    python3 gen.py 20000 [seed] [--queries Q] [--k K]

Проверяющий скрипт вызывает генератор сам (python3 gen.py N); ручной запуск
нужен для своих файлов к отчёту. Для отчёта берите свой seed — его выдаёт
преподаватель.
"""
import argparse
import random

COMMON = """и в на с по не для что это как вы ваш мы от до за о у из к
сегодня завтра день неделя пожалуйста спасибо здравствуйте привет добрый
""".split()

CLASSES = {
    "ham": """совещание отчёт кабинет проект документы правки встреча
календарь конференция договор счёт оплата квитанция репозиторий ветка
задачи трекер сервер конфигурация доступ тестирование спецификация интерфейс
коллеги отдел кадров урок семинар поход маршрут мама продукты список ключи
соседка статья структура материалы сертификат адрес бумага резюме таблица
трафик анализ повестка ноутбук пропуск вложение обсудим перенесена""".split(),
    "spam": """поздравляем выиграли приз скидка предложение курс заработок
купить только успейте крем омоложение кредит одобрение анкета работайте
дома ежедневно премиум подписка код авиабилеты ограничено подарочная карта
лекарство рецепт таблетка похудения бесплатно продвиньте лиды вебинар
миллионером гарантирован распродажа инвестиционной доход реферальная бонус
акция эксклюзив трейдеров секретными продаж отзывы гарантии суперпредложение
демо регистрируйтесь""".split(),
    "phish": """внимание учётная запись отключена подозрительной активности
подтвердите данные ссылке блокировки служба безопасности банка попытка
входа смените пароль платёж реквизиты карты кабинете отменён доставкой
курьер восстановления корпоративной логин администрация облако учётные
личности паспорта портале банковские зарплаты задержится операции аккаунта
устройство верификации смс авторизуйтесь""".split(),
}


def doc(rng, words, length, noise_space):
    out = []
    for _ in range(length):
        r = rng.random()
        if r < 0.55:
            out.append(rng.choice(words))
        elif r < 0.85:
            out.append(rng.choice(COMMON))
        else:
            out.append(f"w{rng.randrange(noise_space)}")
    if rng.random() < 0.3:
        out[0] = out[0].capitalize()
    return " ".join(out) + rng.choice([".", "!", "", " — ок."])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("n", type=int, nargs="?", default=10000)
    ap.add_argument("seed", type=int, nargs="?", default=1)
    ap.add_argument("--queries", type=int, default=20)
    ap.add_argument("--k", type=int, default=10)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    noise = max(100, a.n * 2)          # словарь растёт линейно с N
    labels = ["ham"] * 5 + ["spam"] * 3 + ["phish"] * 2
    out = [f"K {a.k}", "TRAIN"]
    for _ in range(a.n):
        label = rng.choice(labels)
        out.append(f"{label} || {doc(rng, CLASSES[label], rng.randint(6, 20), noise)}")
    out.append("QUERY")
    for _ in range(a.queries):
        label = rng.choice(labels)
        out.append(doc(rng, CLASSES[label], rng.randint(6, 20), noise))
    print("\n".join(out))


if __name__ == "__main__":
    main()
